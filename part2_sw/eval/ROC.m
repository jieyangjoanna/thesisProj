function [TPR, FPR] = ROC( blood_data, non_blood_data)
% This function generates ROC (Receiver Operating Characteristics) curve to
% evaluate target detection performance. 

%   blood_data is the input target n-by-1 detection score sorted with descending order
%   non_blood_data is the input non-target m-by-1 detection score sorted
%   with descending order. n is the number of target, m is the number of
%   non-target.

%   Output TPR is the True positive rate, FPR is False positive rate.
%   The target has to be enough so that is has a meaning statistics. If the 
%   target is too small, we can plot target detection rate as a function of
%   FPR, generated by simply counting the false alarm occurences as each
%   target pixel is detected.

blood_sample = length(blood_data);
non_blood_sample = length(non_blood_data);
threshold = unique(blood_data);
threshold = sort(threshold,'descend');
TPR = zeros(length(threshold),1);
FPR = zeros(length(threshold),1);
for i = 1: length(threshold)
    TPR(i) = length(find(blood_data >= threshold(i)))/blood_sample;
    FPR(i) = length(find(non_blood_data >= threshold(i)))/non_blood_sample;
end

end

